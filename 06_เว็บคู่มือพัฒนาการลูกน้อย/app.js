function handleGlobalSearch(query) {
  const keyword = query.trim().toLowerCase();
  const searchView = document.getElementById('search-view');
  const resultsGrid = document.getElementById('searchResultsGrid');
  const keywordSpan = document.getElementById('searchKeyword');
  const clearBtn = document.getElementById('clearSearchBtn');

  if (!keyword) {
    clearSearch();
    return;
  }

  if (clearBtn) clearBtn.classList.remove('hidden');
  searchView.classList.remove('hidden');
  keywordSpan.textContent = query;

  // Search across stages, activities, language, math, pedagogies, and discipline
  const results = [];

  // Search stages
  stagesData.forEach(s => {
    const text = (s.title + ' ' + s.subtitle + ' ' + s.recommendedToys + ' ' + s.keyTeachings.map(t => t.title + ' ' + t.desc).join(' ')).toLowerCase();
    if (text.includes(keyword)) {
      results.push({
        type: "หมวดพัฒนาการตามวัย",
        title: s.title,
        badge: s.badge,
        desc: s.subtitle,
        action: () => { switchTab('milestones'); scrollToAgeSection(s.id); }
      });
    }
  });

  // Search activities
  activitiesData.forEach(a => {
    const text = (a.title + ' ' + a.materials + ' ' + a.howTo + ' ' + a.benefits + ' ' + a.domainLabel).toLowerCase();
    if (text.includes(keyword)) {
      results.push({
        type: "หมวดกิจกรรมการเล่น",
        title: a.title,
        badge: a.domainLabel,
        desc: `อุปกรณ์: ${a.materials} | วิธีเล่น: ${a.howTo}`,
        action: () => { switchTab('activities'); }
      });
    }
  });

  // Search pedagogies
  pedagogiesData.forEach(p => {
    const text = (p.name + ' ' + p.tagline + ' ' + p.philosophy + ' ' + p.suitableFor).toLowerCase();
    if (text.includes(keyword)) {
      results.push({
        type: "แนวโรงเรียนอนุบาล",
        title: p.name,
        badge: p.tagline,
        desc: p.philosophy,
        action: () => { switchTab('kindergarten'); }
      });
    }
  });

  // Search discipline phrases
  phrasesData.forEach(ph => {
    const text = (ph.trigger + ' ' + ph.traditional + ' ' + ph.positive + ' ' + ph.psychology).toLowerCase();
    if (text.includes(keyword)) {
      results.push({
        type: "วินัยเชิงบวก",
        title: ph.trigger,
        badge: "คำพูดเชิงบวก",
        desc: `เปลี่ยนเป็น: "${ph.positive}" (${ph.psychology})`,
        action: () => { switchTab('discipline'); }
      });
    }
  });

  if (results.length === 0) {
    resultsGrid.innerHTML = `
      <div class="col-span-full text-center py-8 bg-white rounded-2xl border border-warm-200">
        <p class="text-warm-500 text-xs sm:text-sm">ไม่พบเนื้อหาที่ตรงกับคำว่า "${query}" กรุณาลองใช้คำอื่น เช่น โฟนิกส์, อนุบาล, สองภาษา, อารมณ์</p>
      </div>
    `;
    return;
  }

  resultsGrid.innerHTML = results.slice(0, 9).map(r => `
    <div class="bg-white p-4 rounded-2xl border border-warm-200 shadow-sm flex flex-col justify-between hover:border-coral-300 transition-colors">
      <div>
        <span class="text-[11px] font-bold text-coral-600 uppercase tracking-wider block mb-1">${r.type}</span>
        <h4 class="font-bold text-warm-900 text-sm mb-1">${r.title}</h4>
        <p class="text-xs text-warm-600 line-clamp-2">${r.desc}</p>
      </div>
      <button onclick="(${r.action.toString()})()" class="mt-3 text-xs font-semibold text-coral-600 hover:underline text-left">
        เปิดดูหน้านี้ →
      </button>
    </div>
  `).join('');

  lucide.createIcons();
}

