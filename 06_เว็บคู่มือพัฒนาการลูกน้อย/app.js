// 3.7 Render Milestone Checklist
function renderChecklist() {
  const container = document.getElementById('checklistSections');
  if (!container) return;

  let totalItems = 0;
  let checkedItems = 0;

  checklistData.forEach(sec => {
    sec.items.forEach(it => {
      totalItems++;
      if (checklistState[it.id]) checkedItems++;
    });
  });

  const percent = totalItems === 0 ? 0 : Math.round((checkedItems / totalItems) * 100);
  const percentEl = document.getElementById('checklistProgressPercent');
  const detailEl = document.getElementById('checklistProgressDetail');
  if (percentEl) percentEl.textContent = `${percent}%`;
  if (detailEl) detailEl.textContent = `ทำได้แล้ว ${checkedItems} จากทั้งหมด ${totalItems} รายการ`;

  container.innerHTML = checklistData.map(sec => `
    <div class="space-y-3">
      <h4 class="font-bold text-base text-warm-900 pb-1 border-b border-warm-100 flex items-center gap-2">
        <i data-lucide="calendar" class="w-4 h-4 text-mint-500"></i>
        <span>${sec.category}</span>
      </h4>

      <div class="grid grid-cols-1 md:grid-cols-2 gap-2.5">
        ${sec.items.map(it => {
          const isChecked = !!checklistState[it.id];
          return `
            <label class="flex items-start gap-3 p-3 rounded-xl border ${isChecked ? 'bg-mint-50/70 border-mint-200' : 'bg-warm-50 border-warm-200'} cursor-pointer hover:bg-mint-50/40 transition-colors">
              <input 
                type="checkbox" 
                class="mt-1 w-4 h-4 rounded text-mint-600 focus:ring-mint-500 border-warm-300"
                ${isChecked ? 'checked' : ''}
                onchange="toggleChecklistItem('${it.id}', this.checked)"
              >
              <span class="text-xs sm:text-sm ${isChecked ? 'text-warm-900 font-medium line-through opacity-75' : 'text-warm-800'}">
                ${it.text}
              </span>
            </label>
          `;
        }).join('')}
      </div>
    </div>
  `).join('');
}

function toggleChecklistItem(id, checked) {
  checklistState[id] = checked;
  localStorage.setItem('kiddev_checklist', JSON.stringify(checklistState));
  renderChecklist();
  lucide.createIcons();
}

function resetChecklist() {
  if (confirm('คุณต้องการล้างข้อมูลการเช็คพัฒนาการทั้งหมดใช่หรือไม่?')) {
    checklistState = {};
    localStorage.removeItem('kiddev_checklist');
    renderChecklist();
    lucide.createIcons();
  }
}


