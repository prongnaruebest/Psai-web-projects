// Kindergarten Quiz Logic
function renderQuizStep() {
  const container = document.getElementById('quizContainer');
  if (!container) return;

  if (currentQuizStep >= quizData.length) {
    renderQuizResult();
    return;
  }

  const q = quizData[currentQuizStep];
  container.innerHTML = `
    <div class="space-y-4">
      <div class="flex items-center justify-between text-xs text-warm-500">
        <span>ข้อที่ ${currentQuizStep + 1} จาก ${quizData.length}</span>
        <div class="flex gap-1">
          ${quizData.map((_, i) => `
            <div class="w-6 h-1.5 rounded-full ${i <= currentQuizStep ? 'bg-coral-500' : 'bg-warm-200'}"></div>
          `).join('')}
        </div>
      </div>

      <h4 class="text-base sm:text-lg font-bold text-warm-900">${q.question}</h4>

      <div class="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-2">
        ${q.options.map((opt, idx) => `
          <button onclick="handleQuizAnswer('${opt.type}')" class="p-4 rounded-2xl border border-warm-200 hover:border-coral-400 hover:bg-coral-50/50 text-left transition-all group flex items-start gap-3">
            <span class="w-6 h-6 rounded-full bg-warm-100 text-warm-700 group-hover:bg-coral-500 group-hover:text-white flex items-center justify-center text-xs font-bold flex-shrink-0 transition-colors">
              ${String.fromCharCode(65 + idx)}
            </span>
            <span class="text-xs sm:text-sm text-warm-800 leading-relaxed">${opt.text}</span>
          </button>
        `).join('')}
      </div>
    </div>
  `;
}

function handleQuizAnswer(type) {
  quizAnswers[type] = (quizAnswers[type] || 0) + 1;
  currentQuizStep++;
  renderQuizStep();
  lucide.createIcons();
}

function renderQuizResult() {
  const container = document.getElementById('quizContainer');
  if (!container) return;

  // Find dominant pedagogy
  let bestType = 'playbased';
  let maxCount = -1;
  for (const [type, count] of Object.entries(quizAnswers)) {
    if (count > maxCount) {
      maxCount = count;
      bestType = type;
    }
  }

  const matchedPed = pedagogiesData.find(p => p.id === bestType) || pedagogiesData[0];

  container.innerHTML = `
    <div class="bg-gradient-to-br from-coral-50 to-honey-50 rounded-2xl p-6 sm:p-8 border border-coral-200 text-center space-y-4">
      <div class="w-16 h-16 rounded-full bg-white shadow-md mx-auto flex items-center justify-center text-3xl">
        ${matchedPed.icon}
      </div>
      <div>
        <span class="text-xs font-bold text-coral-600 uppercase tracking-wider">ผลลัพธ์จากการวิเคราะห์</span>
        <h3 class="text-xl sm:text-2xl font-bold text-warm-900 mt-1">แนวทางที่เหมาะกับครอบครัวคุณมากที่สุดคือ:</h3>
        <p class="text-lg font-bold text-coral-600">${matchedPed.name}</p>
      </div>

      <p class="text-xs sm:text-sm text-warm-700 max-w-lg mx-auto leading-relaxed">
        ${matchedPed.philosophy}
      </p>

      <div class="bg-white/80 p-4 rounded-xl max-w-md mx-auto text-left text-xs space-y-1.5 border border-coral-100">
        <p><strong class="text-warm-900">เหตุผลที่เหมาะสม:</strong> ${matchedPed.suitableFor}</p>
        <p><strong class="text-warm-900">สิ่งที่ควรตระหนัก:</strong> ${matchedPed.watchOut}</p>
      </div>

      <div class="pt-2">
        <button onclick="resetQuiz()" class="text-xs text-warm-600 hover:text-warm-900 underline font-semibold">
          🔄 ทำแบบทดสอบใหม่อีกครั้ง
        </button>
      </div>
    </div>
  `;
}

function resetQuiz() {
  quizAnswers = {};
  currentQuizStep = 0;
  renderQuizStep();
}

