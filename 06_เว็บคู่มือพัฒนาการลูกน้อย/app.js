function toggleBookmark(id, type) {
  const index = bookmarks.findIndex(b => b.id === id);
  if (index >= 0) {
    bookmarks.splice(index, 1);
  } else {
    bookmarks.push({ id, type, addedAt: new Date().toISOString() });
  }
  localStorage.setItem('kiddev_bookmarks', JSON.stringify(bookmarks));
  updateBookmarkBadge();
  
  // Re-render
  if (currentTab === 'milestones') renderMilestones();
  if (currentTab === 'activities') renderActivitiesGrid();
  if (currentTab === 'bookmarks') renderBookmarksView();
  lucide.createIcons();
}

function updateBookmarkBadge() {
  const badge = document.getElementById('bookmarkBadge');
  if (!badge) return;
  if (bookmarks.length > 0) {
    badge.textContent = bookmarks.length;
    badge.classList.remove('hidden');
  } else {
    badge.classList.add('hidden');
  }
}

