export function getChapter(number: number): Chapter | undefined {
  const meta = chapters.find((chapter) => chapter.number === number);
  if (!meta) return undefined;
  return { ...meta, content: sampleParagraphs.map((paragraph, index) => index === 0 ? `${meta.title} — ${paragraph}` : paragraph) };
}

export function getVolume(number: number) { return volumes.find((volume) => volume.number === number); }
